export type LetterCaseMode = "lower" | "upper";

export function getLetterCenterlinePaths(
  raw: string,
  caseMode: LetterCaseMode = "upper",
): string[] {
  const ch = (raw || "A").trim().charAt(0);
  if (caseMode === "lower") {
    const lowerKey = ch.toLowerCase();
    if (LOWERCASE_CENTERLINE_PATHS[lowerKey]) {
      return LOWERCASE_CENTERLINE_PATHS[lowerKey];
    }
  }
  const upperKey = ch.toUpperCase();
  return LETTER_CENTERLINE_PATHS[upperKey] ?? LETTER_CENTERLINE_PATHS.A;
}
